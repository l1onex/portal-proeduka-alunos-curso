/**
 * Bootstrap mínimo do schema `auth` para PostgreSQL direto.
 *
 * Cria:
 * - schema `auth`
 * - extensão `pgcrypto`
 * - tabelas `auth.users`, `auth.identities`, `auth.sessions`
 * - funções `auth.uid()` e `auth.jwt()`
 */
export async function ensureAuthSchema(sql) {
  await sql.unsafe(`
    CREATE SCHEMA IF NOT EXISTS auth;

    CREATE EXTENSION IF NOT EXISTS pgcrypto;

    CREATE TABLE IF NOT EXISTS auth.users (
      instance_id uuid NOT NULL,
      id uuid PRIMARY KEY,
      aud text NOT NULL DEFAULT 'authenticated',
      role text NOT NULL DEFAULT 'authenticated',
      email text NOT NULL,
      encrypted_password text,
      email_confirmed_at timestamptz,
      raw_app_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb,
      raw_user_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    CREATE INDEX IF NOT EXISTS idx_auth_users_email_lower
      ON auth.users (lower(trim(email::text)));

    CREATE TABLE IF NOT EXISTS auth.identities (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
      provider text NOT NULL DEFAULT 'email',
      identity_data jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now(),
      CONSTRAINT auth_identities_user_provider_unique UNIQUE (user_id, provider)
    );

    CREATE TABLE IF NOT EXISTS auth.sessions (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    );

    CREATE OR REPLACE FUNCTION auth.uid()
    RETURNS uuid
    LANGUAGE sql
    STABLE
    AS $$
      SELECT NULL::uuid;
    $$;

    CREATE OR REPLACE FUNCTION auth.jwt()
    RETURNS jsonb
    LANGUAGE sql
    STABLE
    AS $$
      SELECT '{}'::jsonb;
    $$;
  `);
}
